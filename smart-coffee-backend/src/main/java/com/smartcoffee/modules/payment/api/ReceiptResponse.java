package com.smartcoffee.modules.payment.api;

import java.time.Instant;
import java.util.UUID;
import tools.jackson.databind.JsonNode;

/**
 * One receipt as returned by the GET receipt contract (Full-stack wiring §1.3).
 * {@code snapshot} is the IMMUTABLE payload captured at settlement time (money
 * breakdown, tender, exchange-rate trail) — never recomputed from current
 * prices or rates. Statuses: PENDING/PROCESSING (requested, document not issued
 * yet), ISSUED, FAILED (retryable, with a bounded customer-safe reason).
 *
 * <p>An ISSUED receipt includes a short-lived signed {@code downloadUrl}
 * generated by the existing private-object policy. The internal object key is
 * never exposed, and no storage credential is ever returned. An order with no
 * settled payment has no receipts: the endpoint returns an empty list, not a
 * 404 — the order itself was already validated.
 */
public record ReceiptResponse(
        UUID receiptId,
        String receiptNumber,
        UUID paymentId,
        UUID orderId,
        UUID storeId,
        String status,
        JsonNode snapshot,
        Instant issuedAt,
        Instant createdAt,
        String downloadUrl,
        String mimeType,
        Long sizeBytes,
        String checksum,
        String failureReason,
        int attempts,
        Instant lastAttemptAt) {
}
